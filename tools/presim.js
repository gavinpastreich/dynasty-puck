// Precomputed season simulation for the site's first load: runs E.baseSim() (1,500 seasons, fixed seed) on tonight's data
// exactly as the browser would and writes data/sim.js. The app uses it instead of running the simulation on the
// visitor's device when it still matches: same build, same lineup week and week in progress, same Eastern date, no
// commissioner overrides, no newer live standings (assets/js/app.js boot). Otherwise the browser simulates as before.
//   node tools/presim.js            (the nightly job runs it after the data build)
//   node tools/presim.js --check    (exit 1 if data/sim.js is missing or does not match a fresh run)
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'data', 'sim.js');

global.window = global; global.self = global;
global.document = { addEventListener() {}, querySelector() { return null; }, querySelectorAll() { return []; }, createElement() { return { getContext() { return null; } }; }, head: { appendChild() {} }, documentElement: { dataset: {} } };
const run = (f) => (0, eval)(fs.readFileSync(path.join(ROOT, f), 'utf8') + '\n//# sourceURL=' + f);
['data/league.js', 'data/prospects.js', 'assets/js/engine.js'].forEach(run);
const DP = global.DP, E = DP.E;
E.init();
const etDay = (d) => new Intl.DateTimeFormat('en-CA', { timeZone: 'America/New_York', year: 'numeric', month: '2-digit', day: '2-digit' }).format(d);
const t0 = Date.now(), res = E.baseSim(), ms = Date.now() - t0;
const pre = { built: DP.meta.built, day: etDay(E.now()), lw: E.lockWeek(), nw: E.nowWeek(), n: 1500, ms: ms, res: res };
const js = '/* generated by tools/presim.js - do not edit */\nwindow.DP=window.DP||{};DP.simPre=' + JSON.stringify(pre) + ';\n';
if (process.argv.includes('--check')) {
  const ok = fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8').replace(/"ms":\d+,/, '') === js.replace(/"ms":\d+,/, '');
  console.log(ok ? 'data/sim.js matches a fresh simulation' : 'data/sim.js is missing or out of date');
  process.exit(ok ? 0 : 1);
}
fs.writeFileSync(OUT, js);
console.log('Precomputed season simulation: ' + res.length + ' teams, ' + pre.n + ' seasons in ' + ms + ' ms (build ' + pre.built + ', ET day ' + pre.day + ', lock week ' + (pre.lw === null ? '-' : pre.lw + 1) + ') -> data/sim.js, ' + Math.round(js.length / 1024) + ' KB');
