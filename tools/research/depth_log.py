"""Line and power-play changes: night-to-night differences in Daily Faceoff's depth charts (tools/research/depth.json).

Each night's depth.json is committed by the nightly refresh, so the changes are the differences between consecutive
nights: a skater's line (F1-F4, D1-D3), power-play unit (PP1, PP2) and a goalie's place in the tandem (G1, G2).

    python tools/research/depth_log.py              tonight: compare depth.json with the last committed one (HEAD)
    python tools/research/depth_log.py --backfill   rebuild the log from every night in git (needs a full clone)

Writes raw/<season>/depth/log.json (60 days) and data/depthlog.js (30 days) for the Line Changes page.
"""
import datetime as dt
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
CFG = json.load(open(os.path.join(ROOT, "config", "league.json"), encoding="utf-8"))
RAW = os.path.join(ROOT, *CFG.get("rawFolder", "raw/2026-27").split("/"), "depth")
LOG = os.path.join(RAW, "log.json")
OUT = os.path.join(ROOT, "data", "depthlog.js")
REL = "tools/research/depth.json"
KEEP_DAYS, PUBLISH_DAYS = 60, 30
TOP = {"F1", "F2", "D1", "D2"}  # top-six forwards, top-four defensemen
RANK = {"F1": 1, "F2": 2, "F3": 3, "F4": 4, "D1": 1, "D2": 2, "D3": 3, "PP1": 1, "PP2": 2, "G1": 1, "G2": 2}


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout


def roles(team):
    """{player name: {'line': 'F2', 'pp': 'PP1', 'g': 'G1'}} for one team's depth chart."""
    out = {}
    for k in ("f1", "f2", "f3", "f4", "d1", "d2", "d3"):
        for n in team.get(k) or []:
            out.setdefault(n, {})["line"] = k.upper()
    for k in ("pp1", "pp2"):
        for n in team.get(k) or []:
            out.setdefault(n, {})["pp"] = k.upper()
    for i, n in enumerate((team.get("goalies") or [])[:2]):
        out.setdefault(n, {})["g"] = "G%d" % (i + 1)
    return out


def diff(prev, cur, date):
    """Events between two nights' depth charts. A team whose chart wasn't refreshed (same 'updated') is skipped."""
    ev = []
    for code, t1 in (cur.get("teams") or {}).items():
        t0 = (prev.get("teams") or {}).get(code)
        if not t0 or t0.get("updated") == t1.get("updated"):
            continue
        r0, r1 = roles(t0), roles(t1)
        for name in sorted(set(r0) | set(r1)):
            a, b = r0.get(name, {}), r1.get(name, {})
            for kind in ("line", "pp", "g"):
                x, y = a.get(kind), b.get(kind)
                if x == y or (not x and not y):
                    continue
                if kind == "line" and x and y and x[0] != y[0]:
                    continue  # F <-> D: a listing quirk, not a move
                if kind == "line" and x and y and (x in TOP) == (y in TOP):
                    continue  # a shuffle inside the top six F / top four D, or inside the bottom of the lineup: noise
                up = (y is not None) and (x is None or RANK.get(y, 9) < RANK.get(x, 9))
                ev.append({"d": date, "t": code, "n": name, "k": kind, "from": x or "", "to": y or "", "up": up})
    return ev


def merge(events):
    """One event per player, kind and day: two runs on the same day (a re-run, or the chart updated twice) are merged
    into where he started the day and where he ended it; a move undone the same day is dropped."""
    by = {}
    for e in events:  # events arrive in the order they happened
        key = (e["d"], e["t"], e["n"], e["k"])
        if key in by:
            by[key] = dict(by[key], to=e["to"])
        else:
            by[key] = dict(e)
    out = []
    for key in sorted(by):
        e = by[key]
        if e["from"] == e["to"]:
            continue
        e["up"] = bool(e["to"]) and (not e["from"] or RANK.get(e["to"], 9) < RANK.get(e["from"], 9))
        out.append(e)
    return out


def load():
    if os.path.exists(LOG):
        with open(LOG, encoding="utf-8") as f:
            return json.load(f)
    return {"events": []}


def save(log):
    cut = (dt.date.today() - dt.timedelta(days=KEEP_DAYS)).isoformat()
    log["events"] = evs = merge([e for e in log["events"] if e["d"] >= cut])
    os.makedirs(RAW, exist_ok=True)
    with open(LOG, "w", encoding="utf-8") as f:
        f.write('{\n  "_what": "Line / power-play / goalie-order changes between consecutive nights of Daily Faceoff depth charts (tools/research/depth_log.py). k: line, pp or g; up = moved up.",\n  "events": [\n')
        f.write(",\n".join("    " + json.dumps(e, ensure_ascii=False) for e in evs))
        f.write("\n  ]\n}\n")
    pub_cut = (dt.date.today() - dt.timedelta(days=PUBLISH_DAYS)).isoformat()
    pub = {"updated": dt.datetime.utcnow().strftime("%Y-%m-%dT%H:%M"), "events": [e for e in evs if e["d"] >= pub_cut]}
    js = "/* generated by tools/research/depth_log.py - do not edit */\nwindow.DP=window.DP||{};DP.depthLog=" + json.dumps(pub, separators=(",", ":"), ensure_ascii=False) + ";\n"
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(js)
    print(f"Line changes: {len(evs)} events kept, {len(pub['events'])} published (since {pub_cut})")


def main():
    log = load()
    with open(os.path.join(ROOT, REL), encoding="utf-8") as f:
        cur = json.load(f)
    if "--backfill" in sys.argv:
        days = {}
        for line in git("log", "--format=%H_%cd", "--date=short", "--", REL).split():
            h, d = line.split("_")
            days.setdefault(d, h)  # newest commit of each day
        order = sorted(days)
        prev = None
        log = {"events": []}
        for d in order:
            try:
                snap = json.loads(git("show", f"{days[d]}:{REL}"))
            except Exception as e:  # an unreadable night: skip it
                print(f"  ! {d}: {e}")
                continue
            if prev is not None:
                log["events"] += diff(prev, snap, d)
            prev = snap
        if prev is not None:
            log["events"] += diff(prev, cur, cur.get("updated") or dt.date.today().isoformat())
        print(f"  backfill: {len(order)} nights")
    else:
        try:
            prev = json.loads(git("show", f"HEAD:{REL}"))
        except Exception:
            prev = None
        if prev:
            log["events"] += diff(prev, cur, cur.get("updated") or dt.date.today().isoformat())
    save(log)


if __name__ == "__main__":
    main()
